t('yalta пт 11:00', r('2026-10-23 11:00', true, 'yalta'), 'run 2026-10-27..2026-10-27');
t('simf сб', r('2026-10-24 12:00', true, 'simf'), 'run 2026-10-27..2026-10-27');
