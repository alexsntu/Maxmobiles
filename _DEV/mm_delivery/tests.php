<?php
/** Проверки правил RULES.md. Запуск: php tests.php (PHP 7.4+). */

require __DIR__ . '/engine.php';

$fail = 0;
$n = 0;
function t($name, $got, $want)
{
    global $fail, $n;
    $n++;
    if ($got !== $want) {
        $fail++;
        echo "FAIL $name: получили «$got», ждали «$want»\n";
    }
}
function at($s)
{
    return new DateTimeImmutable($s, new DateTimeZone('Europe/Moscow'));
}
/** Срок одной строкой: «2026-10-19..2026-10-19» */
function r($now, $stock, $zone)
{
    $e = mm_dd_estimate(at($now), $stock, $zone);

    return $e ? $e['kind'] . ' ' . $e['from']->format('Y-m-d') . '..' . $e['to']->format('Y-m-d') : 'null';
}

t('2026-10-19 – понедельник', at('2026-10-19')->format('N'), '1');

// Севастополь, в наличии: до 19:00 – сегодня, с 19:00 – завтра
t('sev 09:00', r('2026-10-19 09:00', true, 'sev'), 'pickup 2026-10-19..2026-10-19');
t('sev 18:59', r('2026-10-19 18:59', true, 'sev'), 'pickup 2026-10-19..2026-10-19');
t('sev 19:00', r('2026-10-19 19:00', true, 'sev'), 'pickup 2026-10-20..2026-10-20');
t('sev 23:30', r('2026-10-19 23:30', true, 'sev'), 'pickup 2026-10-20..2026-10-20');
$e = mm_dd_estimate(at('2026-10-19 12:00'), true, 'sev');
